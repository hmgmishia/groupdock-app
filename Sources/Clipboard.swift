import AppKit
import Foundation

/// クリップボード履歴の 1 件。テキスト・画像・ファイルの 3 種類。
/// 画像は容量が大きいので、本体は別のファイル（`ClipboardStore.imageDirectory`・暗号化）に置き、ここには名前と
/// 一覧用の超縮小画像（`thumbnail`）だけ持つ。一覧は縮小画像で描き、元画像は押したときだけ復号する。
struct ClipEntry: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    var kind: Kind
    /// テキスト本体、またはファイルのパス（改行区切り）。画像は空。
    var text: String = ""
    /// 画像ファイルの名前（`imageDirectory` の中）。画像以外は nil。
    var imageName: String? = nil
    /// 一覧用の超縮小画像（PNG）。索引と一緒に暗号化して保存する。画像以外は nil。
    var thumbnail: Data? = nil
    var date = Date()
    /// 同じ内容かを見分ける印（テキストは本文、画像は中身の要約、ファイルはパス）。
    var fingerprint: String
    /// 先頭に固定する（件数の上限で消さない）。
    var pinned = false

    /// 一覧に出す 1 行の見出し。
    var title: String {
        switch kind {
        case .text:
            let line = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
            return String(line.prefix(80))
        case .image:
            return "画像"
        case .files:
            let names = text.split(separator: "\n").map { path -> String in
                path.split(separator: "/").last.map(String.init) ?? String(path)
            }
            guard names.count > 2 else { return names.joined(separator: "、") }
            return "\(names[0])、\(names[1]) ほか \(names.count - 2) 件"
        }
    }
}

/// 履歴の並び（純粋関数）。同じ内容は 1 件にまとめて先頭へ、固定は消さず、上限を超えたら古いものから消す。
enum ClipboardHistory {
    static let limit = 50

    /// `entry` を先頭に足す。同じ内容があればそれを取り除き、先頭へ移す（固定と画像の名前は引き継ぐ）。
    static func adding(_ entry: ClipEntry, to list: [ClipEntry], limit: Int = ClipboardHistory.limit) -> [ClipEntry] {
        var item = entry
        var rest = list
        if let same = rest.firstIndex(where: { $0.fingerprint == entry.fingerprint }) {
            item.pinned = rest[same].pinned
            item.id = rest[same].id
            // 同じ画像は、最初に保存したファイルと縮小画像を使い続ける（同じ画像を何度も保存しない）。
            if let oldName = rest[same].imageName { item.imageName = oldName }
            if let oldThumb = rest[same].thumbnail { item.thumbnail = oldThumb }
            rest.remove(at: same)
        }
        var kept = 0
        return ([item] + rest).filter { candidate in
            if candidate.pinned { return true }
            kept += 1
            return kept <= limit
        }
    }

    /// 履歴から無くなった画像の名前（ファイルを消すため）。
    static func droppedImages(before: [ClipEntry], after: [ClipEntry]) -> [String] {
        let keep = Set(after.compactMap(\.imageName))
        return before.compactMap(\.imageName).filter { !keep.contains($0) }
    }

    /// 固定を切り替える。
    static func togglingPin(_ id: UUID, in list: [ClipEntry]) -> [ClipEntry] {
        list.map { entry in
            var copy = entry
            if entry.id == id { copy.pinned.toggle() }
            return copy
        }
    }

    /// 既に履歴にある、秘密に見えるテキストを除く（以前の版で保存されたものの掃除）。
    /// 固定したものは、利用者が選んだので残す。画像・ファイルは対象にしない。
    static func purgingSecrets(_ list: [ClipEntry]) -> [ClipEntry] {
        list.filter { $0.pinned || $0.kind != .text || !ClipboardPolicy.looksSecret($0.text) }
    }
}

/// 保存してはいけない内容の判定（純粋関数）。
enum ClipboardPolicy {
    /// パスワード管理アプリなどが付ける「機密・一時」の印（nspasteboard.org の取り決め）。
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// コピー元がこれらのアプリなら、印が無くても保存しない（パスワード管理アプリ・キーチェーン）。
    static let secretSourcePrefixes = [
        "com.1password", "com.agilebits", "com.apple.keychainaccess", "com.apple.Passwords",
        "com.bitwarden", "org.keepassxc", "com.lastpass", "com.dashlane", "in.sinew.Enpass", "com.enpass",
    ]

    /// 機密の印があるか、コピー元がパスワード管理アプリなら保存しない。
    static func shouldRecord(types: [String], sourceBundleID: String? = nil) -> Bool {
        if types.contains(where: { concealedTypes.contains($0) }) { return false }
        if let sourceBundleID, secretSourcePrefixes.contains(where: { sourceBundleID.hasPrefix($0) }) { return false }
        return true
    }

    /// 印が無くても、秘密に見えるテキストか（鍵・トークン・カード番号・パスワード状）。
    /// 見逃しより誤検出の方が害が小さいので、迷うものは秘密として扱う。ただし URL・パス・メールは除く。
    static func looksSecret(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.contains("-----BEGIN"), trimmed.contains("PRIVATE KEY") { return true }
        let tokenPatterns = [
            "^(ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36,}$", "^github_pat_[A-Za-z0-9_]{22,}$",
            "^(AKIA|ASIA)[0-9A-Z]{16}$", "^sk-[A-Za-z0-9_-]{20,}$", "^xox[baprs]-[A-Za-z0-9-]{10,}$",
            "^eyJ[A-Za-z0-9_-]+\\.[A-Za-z0-9_-]+\\.[A-Za-z0-9_-]+$",
        ]
        if tokenPatterns.contains(where: { trimmed.range(of: $0, options: .regularExpression) != nil }) { return true }
        if isCardNumber(trimmed) { return true }
        return looksLikePassword(trimmed)
    }

    /// 13〜19 桁（空白・ハイフン区切り可）で、Luhn を満たすもの。
    private static func isCardNumber(_ text: String) -> Bool {
        let digits = text.filter { $0 != " " && $0 != "-" }
        guard (13...19).contains(digits.count), digits.allSatisfy(\.isASCII), digits.allSatisfy(\.isNumber),
              text.allSatisfy({ $0.isNumber || $0 == " " || $0 == "-" }) else { return false }
        var sum = 0
        for (index, char) in digits.reversed().enumerated() {
            var value = char.wholeNumberValue ?? 0
            if index % 2 == 1 { value *= 2; if value > 9 { value -= 9 } }
            sum += value
        }
        return sum % 10 == 0
    }

    /// 空白の無い 1 語で、大文字・小文字・数字・記号をすべて含む 8〜64 文字。URL・パス・メールは除く。
    private static func looksLikePassword(_ text: String) -> Bool {
        guard (8...64).contains(text.count), !text.contains(where: \.isWhitespace) else { return false }
        if text.contains("://") || text.hasPrefix("/") || text.hasPrefix("~") { return false }
        if text.range(of: "^[^@\\s]+@[^@\\s]+\\.[A-Za-z]{2,}$", options: .regularExpression) != nil { return false }
        let symbols = Set("!@#$%^&*()+=<>?{}[]|~`;'\"\\")
        return text.contains(where: \.isLowercase) && text.contains(where: \.isUppercase)
            && text.contains(where: \.isNumber) && text.contains(where: { symbols.contains($0) })
    }

    /// 長すぎるテキストは保存しない（履歴ファイルが膨らむため）。
    static let maxTextLength = 20_000
    /// 大きすぎる画像は保存しない（バイト）。
    static let maxImageBytes = 15 * 1024 * 1024

    static func acceptsText(_ text: String) -> Bool {
        !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && text.count <= maxTextLength
    }

    static func acceptsImage(byteCount: Int) -> Bool { byteCount > 0 && byteCount <= maxImageBytes }
}

/// クリップボードの中身から、履歴の 1 件を作る（純粋関数）。
enum ClipboardParse {
    /// 画像データの要約。サイズと先頭・末尾の一部で決める（同じ画像を 1 件にまとめるため。暗号用ではない）。
    static func imageFingerprint(_ data: Data) -> String {
        var hash: UInt64 = 1_469_598_103_934_665_603
        func mix(_ bytes: Data) {
            for byte in bytes { hash = (hash ^ UInt64(byte)) &* 1_099_511_628_211 }
        }
        mix(data.prefix(4096))
        mix(data.suffix(4096))
        return "image:\(data.count):\(String(hash, radix: 16))"
    }

    static func text(_ string: String) -> ClipEntry? {
        guard ClipboardPolicy.acceptsText(string), !ClipboardPolicy.looksSecret(string) else { return nil }
        return ClipEntry(kind: .text, text: string, fingerprint: "text:" + string)
    }

    static func files(_ paths: [String]) -> ClipEntry? {
        let list = paths.filter { !$0.isEmpty }
        guard !list.isEmpty else { return nil }
        let joined = list.joined(separator: "\n")
        return ClipEntry(kind: .files, text: joined, fingerprint: "files:" + joined)
    }

    static func image(_ data: Data, name: String, thumbnail: Data? = nil) -> ClipEntry? {
        guard ClipboardPolicy.acceptsImage(byteCount: data.count) else { return nil }
        return ClipEntry(kind: .image, imageName: name, thumbnail: thumbnail, fingerprint: imageFingerprint(data))
    }
}

/// 画像を書き出すときのファイル名（純粋関数）。Finder で使えない文字（: と /）は入れない。
enum ClipboardExport {
    static func suggestedName(date: Date, timeZone: TimeZone = .current) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.timeZone = timeZone
        formatter.dateFormat = "yyyy-MM-dd HH.mm.ss"
        return "クリップボード \(formatter.string(from: date)).png"
    }
}

/// 一覧用の超縮小画像（純粋な計算）。長辺を `side` に収める大きさを決める。
enum ClipboardThumbnail {
    /// 一覧の絵は 32pt。2 倍の画面でも足りるよう 64px にする（これより小さくはしない）。
    static let side: CGFloat = 64

    /// 元の大きさから、縦横比を保って長辺が `side` になる大きさ。元が小さければ拡大しない。
    static func size(for original: CGSize, side: CGFloat = ClipboardThumbnail.side) -> CGSize {
        guard original.width > 0, original.height > 0 else { return .zero }
        let scale = min(1, side / max(original.width, original.height))
        return CGSize(width: max(1, (original.width * scale).rounded()), height: max(1, (original.height * scale).rounded()))
    }
}
